<h2>Understanding the Client Card</h2>
<p>Each entry in Besdex is represented by a detailed card that provides all the essential information needed for effective outreach:</p>

<div class="bg-blue-50 p-4 sm:p-8 rounded-xl border border-blue-100 my-10 shadow-sm">
    <h3 class="text-blue-900 mt-0 flex items-center gap-2">
        <i data-lucide="info" class="w-5 h-5"></i>
        Card Breakdown
    </h3>
    
    <div class="grid grid-cols-1 md:grid-cols-2 gap-8 mt-6">
        <div>
            <h4 class="font-bold text-gray-900 m-0">Identity & Priority</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Displays the <strong>Company Name</strong>, client type (e.g., New Client), and a color-coded <strong>Priority Level</strong> (e.g., Medium Priority) to help you focus on the most important leads.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Communication Channels</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Quick access to <strong>Email</strong> and <strong>Phone</strong> details. The card also features direct integration icons for <strong>WhatsApp, Phone, Email, and Chat</strong>, allowing you to reach out with a single click.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Lead Source & Notes</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Identify where the lead came from (e.g., <em>Besdex, Web, Referral</em>) and review any internal notes or context added by your team.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Action & History</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Use the <strong>"Take Action"</strong> button to update the lead's status or record a new interaction. The history log at the bottom shows when the last action was taken.</p>
        </div>
    </div>
</div>

<h2>Module Purpose</h2>
<p>The primary purpose of Besdex is to ensure that no relationship is neglected. It serves as:</p>
<ul class="list-disc ml-6 space-y-3 text-gray-700">
    <li><strong>A Sales Pipeline:</strong> Move prospects through the tabs from 'Lead' to 'Qualified' and finally to 'Clients'.</li>
    <li><strong>A Data Repository:</strong> Centralize all client contact info and interaction history.</li>
    <li><strong>Efficiency Tool:</strong> Use <strong>"Import from Excel"</strong> to bulk-add hundreds of leads instantly and the <strong>Search</strong> bar to find them by name as your database grows.</li>
</ul>

<div class="p-4 bg-yellow-50 border border-yellow-100 rounded-lg text-sm text-yellow-800 italic mt-10">
    <strong>Pro-Tip:</strong> Regularly use the "Take Action" feature to keep your leads moving through the pipeline and maintain an accurate "last action" timestamp.
</div>
