<h2>The Leave Portal Dashboard</h2>
<p>Your dashboard provides real-time tracking of your leave requests. You can monitor the <strong>Status</strong> of your applications (Pending, Approved, or Rejected) and filter your history by <strong>Leave Type</strong> or <strong>Status</strong> using the dropdown menus. Each entry in the table shows the leave dates, total days, and the date the application was submitted.</p>

<h2>How to Apply for Leave</h2>
<p>To request time off, click the <strong>"+ Apply Leave"</strong> button at the top right of the portal. This will open the <strong>"Apply for Leave"</strong> form. It is important to provide complete and accurate information to ensure your request is processed efficiently by your manager.</p>

