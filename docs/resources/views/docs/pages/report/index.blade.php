        <ul class="mt-2 text-xs text-purple-800 space-y-1 list-disc ml-4">
            <li>Mention <strong>results and outcomes</strong>, not just a list of activities.</li>
            <li>Clearly call out any <strong>blockers</strong> that need manager intervention.</li>
            <li>List 1-2 <strong>focus items</strong> for the next working day to stay organized.</li>
        </ul>
    </div>
