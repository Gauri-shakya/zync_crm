<h2>The Reports Dashboard</h2>
<p>The dashboard provides an immediate overview of your reporting consistency and productivity metrics. Below the summary cards, the <strong>Recent Reports</strong> table allows you to filter and review your past submissions by status, role, or specific date ranges.</p>

<h2>Creating a Daily Report</h2>
<p>To submit your work for the day, click the <strong>"+ New Report"</strong> button. This opens the <strong>"Create Daily Report"</strong> form, which is designed for clarity and professional logging.</p>

<div class="bg-purple-50 p-8 rounded-xl border border-purple-100 my-10">
    <h3 class="text-purple-900 mt-0">Daily Report Form Guide</h3>
    <p class="text-purple-800 mb-6">A well-documented report helps your managers understand your impact and resolve blockers quickly.</p>
    
    <div class="grid grid-cols-1 md:grid-cols-2 gap-8">
        <div>
            <h4 class="font-bold text-gray-900 mb-1">Date & Status</h4>
            <p class="text-sm text-gray-700">Select the working day you are reporting for and your overall completion status for that day. The <strong>Quick Preview</strong> card on the right will update in real-time as you fill out the form.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 mb-1">Tasks & Time Spent</h4>
            <p class="text-sm text-gray-700">List the key tasks you worked on. Use the <strong>"+ Add Task"</strong> button to add multiple entries. For each task, specify the time spent (in hours or minutes). This granularity helps in accurate resource tracking.</p>
        </div>

        <div class="md:col-span-2">
            <h4 class="font-bold text-gray-900 mb-1">Executive Summary</h4>
            <p class="text-sm text-gray-700">Provide a concise summary of your main accomplishments. This is also the place to mention any <strong>blockers</strong> or dependencies that are slowing you down, and your focus items for tomorrow.</p>
        </div>
    </div>

    <div class="mt-8 p-4 bg-white rounded-lg border border-purple-200">
