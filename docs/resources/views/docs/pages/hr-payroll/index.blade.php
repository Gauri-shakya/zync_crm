<h1>Automated HR &amp; Payroll</h1>
<p>Automate your HR operations from attendance tracking to automated salary slip generation.</p>
<h2>Key Features</h2>
<ul>
<li><strong>Attendance &amp; Leaves</strong>: Track employee attendance and manage leave requests.</li>
<li><strong>Automated Payroll</strong>: Generate salary slips automatically based on attendance and earnings.</li>
<li><strong>Employee Self-Portal</strong>: Give employees access to their own profile, attendance, and salary slips.</li>
</ul>
<h2>How to Set Up HR</h2>
<ol>
<li><strong>Add Employees</strong>: Create profiles for each team member.</li>
<li><strong>Define Departments</strong>: Organize employees into departments for better management.</li>
<li><strong>Configure Payroll Settings</strong>: Set up salary structures, deductions, and tax information.</li>
<li><strong>Manage Leaves</strong>: Create leave policies and manage employee leave requests.</li>
</ol>
