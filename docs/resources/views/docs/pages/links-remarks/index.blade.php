<h2>Adding a New Link</h2>
<p>To add a new resource to your manager, click the <strong>"+ Add Link"</strong> button. This opens a configuration form where you can define the properties of your link:</p>

<div class="bg-blue-50 p-8 rounded-xl border border-blue-100 my-10 shadow-sm">
    <h3 class="text-blue-900 mt-0 flex items-center gap-2">
        <i data-lucide="link-2" class="w-5 h-5"></i>
        Link Configuration Form
    </h3>
    
    <div class="grid grid-cols-1 md:grid-cols-2 gap-8 mt-6">
        <div>
            <h4 class="font-bold text-gray-900 m-0">Title</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Give your link a recognizable name, such as <em>"Company LinkedIn Page"</em> or <em>"Main Portfolio Website."</em></p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">URL</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Enter the web address. ZynCRM automatically handles the <em>https://</em> prefix for you, so you can simply type <code>example.com</code>.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Type & Status</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Classify the link as a <strong>Website</strong> or <strong>Social</strong> profile. Set the <strong>Status</strong> to 'Active' to keep it visible in your primary list.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Note (Remarks)</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Use this field to add internal remarks or context about the link. This is useful for tracking the purpose of the link or recording specific login/access details.</p>
        </div>
    </div>

