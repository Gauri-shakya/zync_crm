<h2>Creating Custom Templates</h2>
<p>To ensure your brand's unique voice is consistent across all documents, you can create your own templates. Click the <strong>"+"</strong> icon in the Templates sidebar to open the <strong>"Create New Template"</strong> form.</p>

<div class="bg-indigo-50 p-8 rounded-xl border border-indigo-100 my-10 shadow-sm">
    <h3 class="text-indigo-900 mt-0 flex items-center gap-2">
        <i data-lucide="layers" class="w-5 h-5"></i>
        Template Configuration Guide
    </h3>
    
    <div class="grid grid-cols-1 md:grid-cols-2 gap-8 mt-6">
        <div>
            <h4 class="font-bold text-gray-900 m-0">Select Preset & Name</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Choose a base preset (e.g., Others/Custom) and give your template a clear name like <em>"Q4 SEO Audit"</em>.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Description</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Provide a brief overview of what this template includes to help your team choose the right one for their needs.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Visual Identity</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Select an <strong>Icon</strong> and a <strong>Color Theme</strong> (e.g., Indigo, Blue, Emerald) to make the template easily identifiable in the sidebar.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Save & Use</h4>
            <p class="mt-2 text-sm text-gray-700 leading-relaxed">Once saved, your template will appear in the sidebar list. Click <strong>"+ Use"</strong> to instantly start a new proposal based on those settings.</p>
        </div>
    </div>
</div>

<h2>Starting a New Proposal</h2>
<ul class="list-disc ml-6 space-y-3 text-gray-700">
    <li><strong>Create Blank:</strong> Start from a completely empty canvas or upload your own external document to begin.</li>
    <li><strong>Create from Template:</strong> Select a template card (e.g., Social Media Marketing) and click <strong>"+ Create Proposal"</strong> to pre-fill the document with structured content and styling.</li>
</ul>

<div class="p-4 bg-blue-50 border border-blue-100 rounded-lg text-sm text-blue-800 italic mt-10">
    <strong>Pro-Tip:</strong> Regularly update your templates with your latest service offerings and pricing to ensure your team always sends out the most current information.
</div>
