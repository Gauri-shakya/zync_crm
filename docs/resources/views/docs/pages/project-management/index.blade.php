<h2>The Project Hub Dashboard</h2>
<p>The dashboard features a <strong>Project Hub</strong> where you can monitor your entire portfolio at a glance. Each project is represented by a card that shows:</p>
<ul class="list-disc ml-6 space-y-2 text-gray-700">
    <li><strong>Project Status & Velocity:</strong> A visual progress bar showing the current completion percentage (Velocity).</li>
    <li><strong>Strategist In-Charge:</strong> The lead responsible for the project's success.</li>
    <li><strong>Target Deadline:</strong> A clear countdown to the project's completion date.</li>
    <li><strong>Team Collaboration:</strong> Icons representing the specialized team members assigned to the project.</li>
</ul>

<h2>Launching a New Project</h2>
<p>To begin a new strategic initiative, click the <strong>"+ New Project"</strong> button. This opens the <strong>"Add New Project"</strong> form, where you can define the core parameters of your project.</p>

<div class="bg-blue-50 p-4 sm:p-8 rounded-xl border border-blue-100 my-10">
    <h3 class="text-blue-900 mt-0">Project Configuration Guide</h3>
    <p class="text-blue-800 mb-6">Accurate project setup ensures better resource allocation and more precise analytics.</p>
    
    <div class="grid grid-cols-1 md:grid-cols-2 gap-x-8 lg:gap-x-12 gap-y-8">
        <div>
            <h4 class="font-bold text-gray-900 m-0">Project Title & Client Partner</h4>
            <p class="mt-2 text-sm text-gray-700">Define the project name (e.g., <em>"Q1 Growth Strategy"</em>) and link it to a specific <strong>Client Partner</strong> or company from your CRM database.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Leadership & Teams</h4>
            <p class="mt-2 text-sm text-gray-700">Assign a <strong>Strategist In-Charge</strong> to lead the project and select the <strong>Specialized Team</strong> (Domain) that will execute the deliverables.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Velocity & Priority</h4>
            <p class="mt-2 text-sm text-gray-700">Set the initial <strong>Priority Level</strong> (e.g., Standard, High, Critical) and track the <strong>Velocity (%)</strong> as the project moves from 'Pending' to 'In Progress'.</p>
        </div>

        <div>
            <h4 class="font-bold text-gray-900 m-0">Timeline & Budget</h4>
            <p class="mt-2 text-sm text-gray-700">Input the <strong>Start Date</strong>, <strong>Target Deadline</strong>, and allocated <strong>Budget</strong> to ensure financial and temporal alignment.</p>
        </div>

        <div class="md:col-span-2">
            <h4 class="font-bold text-gray-900 m-0">Project Scope</h4>
            <p class="mt-2 text-sm text-gray-700">The most critical field for clarity. Use this space to <strong>define core objectives, key deliverables, and specific success criteria</strong> for the project.</p>
        </div>
    </div>
</div>

<h2>Managing Existing Projects</h2>
<p>Once a project is created, you can use the <strong>FOCUS</strong> action on the project card to dive deeper into task-level details, or use the <strong>Edit/Delete</strong> icons to make adjustments as the project evolves.</p>
