<h2>Best Practices</h2>
<ul class="list-disc ml-6 space-y-2 text-gray-700">
    <li><strong>Be Specific:</strong> Use detailed titles to find notes quickly without opening them.</li>
    <li><strong>Use Tags Wisely:</strong> Develop a consistent tagging system across your team.</li>
    <li><strong>Leverage Connections:</strong> Always link meeting notes to the relevant project or lead to maintain a clear audit trail.</li>
</ul>
