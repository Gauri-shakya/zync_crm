<h1>Notepad & Thought Canvas</h1>
<p>The <strong>Notepad</strong> module, featured as the <strong>Thought Canvas</strong> in your dashboard, is a powerful tool for capturing ideas, strategies, and meeting insights. It serves as your personal digital workspace within ZynCRM, allowing you to organize your thoughts and connect them to other business activities.</p>

<div class="my-8 rounded-xl overflow-hidden border border-gray-200 shadow-sm bg-white">
    <div class="bg-gray-50 px-4 sm:px-6 py-4 border-b border-gray-200">
        <h3 class="text-gray-900 font-bold m-0 text-lg sm:text-xl">Thought Canvas Dashboard</h3>
    </div>
    <div class="p-4 sm:p-6">
        <p class="leading-relaxed">Your <strong>Thought Canvas</strong> provides a centralized view of all your saved notes. You can easily filter your thoughts by category, time, or sort them to find exactly what you need. If you're just starting, click <strong>"Begin Writing"</strong> or <strong>"+ New Note"</strong> to capture your first brilliant idea.</p>
    </div>
</div>

<h2>Creating a New Note</h2>
<p>When you create a new note, you'll be presented with a few fields that help keep your information organized and searchable. Here is a clear breakdown of each field:</p>

